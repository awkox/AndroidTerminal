    private fun checkSortedRangeTable(table: IntArray, name: String) {
        require(table.size % 2 == 0) { "$name array length must be even" }
        var prevEnd = -1
        for (i in table.indices step 2) {
            val start = table[i]
            val end = table[i + 1]
            require(start <= end && start > prevEnd) { "$name ranges must be sorted and disjoint" }
            prevEnd = end
        }
    }

    private fun inRangeTable(table: IntArray, c: Int): Boolean {
        if (c < table[0]) return false
        var bot = 0
        var top = (table.size ushr 1) - 1
        while (top >= bot) {
            val mid = (bot + top) ushr 1
            val idx = mid shl 1
            val start = table[idx]
            if (start > c) {
                top = mid - 1
            } else {
                val end = table[idx + 1]
                if (end < c) {
                    bot = mid + 1
                } else {
                    return true
                }
            }
        }
        return false
    }

    fun gcbClass(cp: Int): GcbClass {
        if (cp in 0x20..0x7E) return GcbClass.OTHER
        return when {
            cp == 0x0D -> GcbClass.CR
            cp == 0x0A -> GcbClass.LF
            cp == 0x200D -> GcbClass.ZWJ
            cp in 0x1F1E6..0x1F1FF -> GcbClass.REGIONAL_INDICATOR
            cp in 0x1100..0x115F || cp in 0xA960..0xA97C -> GcbClass.L
            cp in 0x1160..0x11A7 || cp in 0xD7B0..0xD7C6 ||
                cp == 0x16D63 || cp in 0x16D67..0x16D6A -> GcbClass.V
            cp in 0x11A8..0x11FF || cp in 0xD7CB..0xD7FB -> GcbClass.T
            cp in 0xAC00..0xD7A3 -> if ((cp - 0xAC00) % 28 == 0) GcbClass.LV else GcbClass.LVT
            inRangeTable(GCB_CONTROL, cp) -> GcbClass.CONTROL
            inRangeTable(GCB_PREPEND, cp) -> GcbClass.PREPEND
            inRangeTable(GCB_EXTEND, cp) -> GcbClass.EXTEND
            inRangeTable(GCB_SPACING_MARK, cp) -> GcbClass.SPACING_MARK
            else -> GcbClass.OTHER
        }
    }

    /**
     * 终端网格非渲染零宽控制与格式断簇字符（C0/C1/格式符等）：既不得附着到前格，也不应作为零宽内容写入单元格。
     * U+00AD（SOFT HYPHEN）在 UAX #29 属于 GCB=Control（前后断簇），但在终端占 1 列可打印宽度，不由本函数丢弃。
     */
    fun isControlOrFormatBreak(cp: Int): Boolean {
        if (cp == 0x00AD) return false
        val gcb = gcbClass(cp)
        return gcb == GcbClass.CONTROL || gcb == GcbClass.CR || gcb == GcbClass.LF
    }

    fun isPrepend(cp: Int): Boolean = gcbClass(cp) == GcbClass.PREPEND

    fun isEmojiTagChar(cp: Int): Boolean = cp in 0xE0020..0xE007F

    fun isExtendedPictographic(cp: Int): Boolean =
        inRangeTable(EXTENDED_PICTOGRAPHIC, cp)

    fun isEmojiModifierBase(cp: Int): Boolean =
        inRangeTable(EMOJI_MODIFIER_BASE, cp)

    fun isInCBLinker(cp: Int): Boolean =
        cp == 0x094D || cp == 0x09CD || cp == 0x0ACD || cp == 0x0B4D || cp == 0x0C4D || cp == 0x0D4D

    fun isInCBConsonant(cp: Int): Boolean =
        inRangeTable(INCB_CONSONANT, cp)

    fun isInCBExtend(cp: Int): Boolean {
        if (cp == 0x200C || isInCBLinker(cp)) return false
        val gcb = gcbClass(cp)
        return gcb == GcbClass.ZWJ || gcb == GcbClass.EXTEND
    }

    private fun isGb11Extend(cp: Int): Boolean =
        gcbClass(cp) == GcbClass.EXTEND

    /**
     * 快速预筛：当 [prevEndsWithPrepend] 为 false 时，ASCII 可打印字符及常规字符绝不会并入前一格，
     * 避免在主路径上复制单元格。
     */
    fun mayMerge(cp: Int, prevEndsWithPrepend: Boolean = false): Boolean {
        if (prevEndsWithPrepend) {
            val gcb = gcbClass(cp)
            return gcb != GcbClass.CONTROL && gcb != GcbClass.CR && gcb != GcbClass.LF
        }
        if (cp in 0x20..0x7E) return false
        val gcb = gcbClass(cp)
        return gcb == GcbClass.EXTEND ||
            gcb == GcbClass.ZWJ ||
            gcb == GcbClass.SPACING_MARK ||
            gcb == GcbClass.REGIONAL_INDICATOR ||
            gcb == GcbClass.L ||
            gcb == GcbClass.V ||
            gcb == GcbClass.T ||
            gcb == GcbClass.LV ||
            gcb == GcbClass.LVT ||
            isExtendedPictographic(cp) ||
            isInCBConsonant(cp)
    }

    /**
     * 依据 Unicode UAX #29 与 UTS #51 判断 [nextCp] 是否应与当前活跃单元格 [cellChars] 合并成同一字素簇。
     */
    fun shouldMerge(cellChars: CharArray, nextCp: Int): Boolean {
        if (cellChars.isEmpty()) return false
        val nextGcb = gcbClass(nextCp)
        if (nextGcb == GcbClass.CONTROL || nextGcb == GcbClass.CR || nextGcb == GcbClass.LF) {
            return false
        }

        val firstCp = Character.codePointAt(cellChars, 0)
        val lastCp = Character.codePointBefore(cellChars, cellChars.size)
        val lastGcb = gcbClass(lastCp)
        if (lastGcb == GcbClass.CONTROL || lastGcb == GcbClass.CR || lastGcb == GcbClass.LF) {
            return false
        }

        if (lastGcb == GcbClass.PREPEND) {
            return true
        }

        if (isEmojiTagChar(nextCp)) {
            return firstCp == 0x1F3F4 && !containsCodePoint(cellChars, 0xE007F)
        }

        if (WcWidth.isEmojiModifier(nextCp)) {
            return endsWithEmojiModifierBase(cellChars)
        }

        if (nextGcb == GcbClass.EXTEND || nextGcb == GcbClass.ZWJ || nextGcb == GcbClass.SPACING_MARK) {
            return true
        }

        if (isExtendedPictographic(nextCp) && lastGcb == GcbClass.ZWJ) {
            return hasGb11BaseBeforeTrailingZwj(cellChars)
        }

        if (nextGcb == GcbClass.REGIONAL_INDICATOR) {
            return Character.codePointCount(cellChars, 0, cellChars.size) == 1 &&
                gcbClass(firstCp) == GcbClass.REGIONAL_INDICATOR
        }

        if (isHangulMerge(lastGcb, nextGcb)) {
            return true
        }

        if (isInCBConsonant(nextCp) && hasIndicConjunctContext(cellChars)) {
            return true
        }

        return false
    }

    /**
     * 在 [shouldMerge] 已返回 true 的前提下，判断当前 1 列宽单元格合并 [nextCp] 后是否应扩展为 2 列宽。
     */
    fun shouldExpandToWide(cellChars: CharArray, prevWidth: Int, nextCp: Int): Boolean {
        if (prevWidth != 1 || cellChars.isEmpty()) return false

        val firstCp = Character.codePointAt(cellChars, 0)
        val lastCp = Character.codePointBefore(cellChars, cellChars.size)
        val cpCount = Character.codePointCount(cellChars, 0, cellChars.size)

        if (gcbClass(lastCp) == GcbClass.PREPEND) {
            return WcWidth.width(nextCp) == 2
        }

        if (WcWidth.isVariationSelector16(nextCp)) {
            return cpCount == 1 && WcWidth.isVs16WideningCandidate(firstCp)
        }

        if (WcWidth.isCombiningEnclosingKeycap(nextCp)) {
            return WcWidth.isKeycapBase(firstCp) &&
                (cpCount == 1 || (cpCount == 2 && WcWidth.isVariationSelector16(lastCp)))
        }

        if (gcbClass(nextCp) == GcbClass.REGIONAL_INDICATOR) {
            return cpCount == 1 && gcbClass(firstCp) == GcbClass.REGIONAL_INDICATOR
        }

        if (WcWidth.isEmojiModifier(nextCp)) {
            return endsWithEmojiModifierBase(cellChars)
        }

        if (isExtendedPictographic(nextCp) && gcbClass(lastCp) == GcbClass.ZWJ) {
            return hasGb11BaseBeforeTrailingZwj(cellChars)
        }

        return false
    }

    private fun containsCodePoint(chars: CharArray, targetCp: Int): Boolean {
        var i = 0
        while (i < chars.size) {
            val cp = Character.codePointAt(chars, i)
            if (cp == targetCp) return true
            i += Character.charCount(cp)
        }
        return false
    }

    private fun endsWithEmojiModifierBase(cellChars: CharArray): Boolean {
        var idx = cellChars.size
        if (idx <= 0) return false
        var cp = Character.codePointBefore(cellChars, idx)
        if (WcWidth.isVariationSelector16(cp)) {
            idx -= Character.charCount(cp)
            if (idx <= 0) return false
            cp = Character.codePointBefore(cellChars, idx)
        }
        return isEmojiModifierBase(cp)
    }

    private fun hasGb11BaseBeforeTrailingZwj(cellChars: CharArray): Boolean {
        var idx = cellChars.size
        if (idx <= 0) return false
        val zwj = Character.codePointBefore(cellChars, idx)
        if (gcbClass(zwj) != GcbClass.ZWJ) return false
        idx -= Character.charCount(zwj)
        while (idx > 0) {
            val cp = Character.codePointBefore(cellChars, idx)
            if (isGb11Extend(cp)) {
                idx -= Character.charCount(cp)
            } else {
                return isExtendedPictographic(cp)
            }
        }
        return false
    }

    private fun isHangulMerge(prevGcb: GcbClass, nextGcb: GcbClass): Boolean {
        if (prevGcb == GcbClass.L &&
            (nextGcb == GcbClass.L || nextGcb == GcbClass.V || nextGcb == GcbClass.LV || nextGcb == GcbClass.LVT)
        ) {
            return true
        }
        if ((prevGcb == GcbClass.LV || prevGcb == GcbClass.V) &&
            (nextGcb == GcbClass.V || nextGcb == GcbClass.T)
        ) {
            return true
        }
        if ((prevGcb == GcbClass.LVT || prevGcb == GcbClass.T) && nextGcb == GcbClass.T) {
            return true
        }
        return false
    }

    private fun hasIndicConjunctContext(cellChars: CharArray): Boolean {
        var idx = cellChars.size
        var seenLinker = false
        while (idx > 0) {
            val cp = Character.codePointBefore(cellChars, idx)
            idx -= Character.charCount(cp)
            when {
                isInCBLinker(cp) -> seenLinker = true
                isInCBExtend(cp) -> Unit
                else -> return seenLinker && isInCBConsonant(cp)
            }
        }
        return false
    }
